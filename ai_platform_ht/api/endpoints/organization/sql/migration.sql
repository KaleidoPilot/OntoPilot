CREATE TABLE ORGANIZATION (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_CODE VARCHAR(64) NOT NULL,
  NAME VARCHAR(255) NOT NULL,
  REMARKS VARCHAR(500) NULL,
  ENABLED TINYINT NOT NULL DEFAULT 1,
  REMOVED TINYINT NOT NULL DEFAULT 0,
  CREATE_USER_ID BIGINT NULL,
  CREATE_USER_NAME VARCHAR(55) NULL,
  CREATE_TIME VARCHAR(55) NULL,
  UPDATE_USER_ID BIGINT NULL,
  UPDATE_USER_NAME VARCHAR(55) NULL,
  UPDATE_TIME VARCHAR(55) NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_ORGANIZATION_ORG_CODE (ORG_CODE),
  KEY IDX_ORGANIZATION_ENABLED (ENABLED, REMOVED)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='公司（组织）';

CREATE TABLE SYSTEM_CONFIG (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_ID BIGINT NOT NULL,
  CONFIG_TYPE TINYINT NOT NULL COMMENT '1数据库 2AI模型 3向量库 4沙箱',
  CONFIG_NAME VARCHAR(100) NOT NULL,
  CONFIG_JSON LONGTEXT NOT NULL,
  ENABLED TINYINT NOT NULL DEFAULT 1,
  REMOVED TINYINT NOT NULL DEFAULT 0,
  CREATE_USER_ID BIGINT NULL,
  CREATE_USER_NAME VARCHAR(55) NULL,
  CREATE_TIME VARCHAR(55) NULL,
  UPDATE_USER_ID BIGINT NULL,
  UPDATE_USER_NAME VARCHAR(55) NULL,
  UPDATE_TIME VARCHAR(55) NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY UK_SYSTEM_CONFIG_ORG_TYPE_NAME (ORG_ID, CONFIG_TYPE, CONFIG_NAME),
  KEY IDX_SYSTEM_CONFIG_ORG_ENABLED (ORG_ID, ENABLED, REMOVED)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='公司系统配置';

